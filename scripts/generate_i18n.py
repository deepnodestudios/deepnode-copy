base_keys = set(data["tr"].keys())
for code, name, eng, flag, dir_ in LANGS:
    if code not in data:
        raise ValueError(f"Missing language: {code}")
    diff = base_keys.symmetric_difference(set(data[code].keys()))
    if diff:
        raise ValueError(f"Key mismatch in {code}: {diff}")

print(f"Validated all {len(LANGS)} languages with {len(base_keys)} keys each!")

# Generate TS code
lines = []
lines.append('export type Language =')
for i, (code, _, _, _, _) in enumerate(LANGS):
    suffix = ";" if i == len(LANGS) - 1 else ""
    lines.append(f'  | "{code}"{suffix}')

lines.append("")
lines.append("export interface LanguageMeta {")
lines.append("  code: Language;")
lines.append("  nativeName: string;")
lines.append("  englishName: string;")
lines.append("  flag: string;")
lines.append('  dir?: "ltr" | "rtl";')
lines.append("}")
lines.append("")
lines.append("export const supportedLanguages: LanguageMeta[] = [")
for code, native, eng, flag, dir_ in LANGS:
    lines.append(f'  {{ code: "{code}", nativeName: "{native}", englishName: "{eng}", flag: "{flag}", dir: "{dir_}" }},')
lines.append("];")
lines.append("")
lines.append("export interface TranslationKeys {")
for k in sorted(base_keys):
    lines.append(f"  {k}: string;")
lines.append("}")
lines.append("")
lines.append("export const translations: Record<Language, TranslationKeys> = {")
for code, _, _, _, _ in LANGS:
    lines.append(f'  "{code}": {json.dumps(data[code], ensure_ascii=False, indent=4)},')
lines.append("};")
lines.append("")

output = "\n".join(lines)
with open("src/i18n.ts", "w", encoding="utf-8") as f:
    f.write(output)

